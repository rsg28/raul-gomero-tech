function seedRand(seed) {
  let h = 2166136261;
  for (let i = 0; i < seed.length; i += 1) {
    h ^= seed.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return () => {
    h += 0x6d2b79f5;
    let t = h;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Stable order per case. The correct id is never left in the first slot. */
export function shuffleOptions(list, seed, correctId) {
  const arr = [...(list || [])];
  const rand = seedRand(String(seed));
  for (let i = arr.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rand() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  if (arr.length > 1 && correctId && arr[0]?.id === correctId) {
    const swap = 1 + Math.floor(rand() * (arr.length - 1));
    [arr[0], arr[swap]] = [arr[swap], arr[0]];
  }
  return arr;
}
