export const byId = Object.fromEntries(IDEAS.map((i) => [i.id, i]));

export function ideasInPath(pathId) {
  return IDEAS.filter((i) => i.path === pathId);
}

export function books() {
  const map = new Map();
  for (const i of IDEAS) {
    const key = i.book;
    if (!map.has(key)) map.set(key, { book: i.book, author: i.author, year: i.year, place: i.place, ideas: [] });
    map.get(key).ideas.push(i);
  }
  return [...map.values()].sort((a, b) => a.year - b.year);
}

export function pathOf(id) {
  return PATHS.find((p) => p.id === id);
}

export function formatYear(y) {
  if (y < 0) return `${Math.abs(y)} a.n.e.`;
  return String(y);
}
